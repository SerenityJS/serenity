import { readFileSync } from "node:fs";
import { lookup } from "node:dns/promises";
import {
  createServer as createHttpServer,
  type IncomingMessage,
  type Server as HttpServer,
  type ServerResponse
} from "node:http";
import { createServer as createHttpsServer } from "node:https";
import { isIP } from "node:net";
import { resolve } from "node:path";

import { Emitter } from "@serenityjs/emitter";
import { Logger, LoggerColors } from "@serenityjs/logger";

import {
  DEFAULT_PORT,
  JOIN_PATH,
  MAX_MESSAGE_SIZE,
  MAX_PENDING_PER_ADDRESS,
  MAX_SIGNAL_SIZE,
  TICK_INTERVAL
} from "../constants";
import { OperatorIdentity, verifyClientIdentity } from "../identity";
import {
  getCandidateAddresses,
  insertCandidates,
  insertIdentity,
  removeIdentity
} from "../sdp";
import { loadNativeBinding, type NativeBinding } from "../native";

import { Connection } from "./connection";

import type { IceUdpMuxListener, PeerConnection } from "node-datachannel";
import type {
  ClientIdentity,
  NetherNetEvents,
  NetherNetServerProperties,
  NetherNetStatus,
  NetworkAddress
} from "../types";

const DefaultNetherNetServerProperties: NetherNetServerProperties = {
  address: "0.0.0.0",
  port: DEFAULT_PORT,
  protocol: 0,
  version: "1.0.0",
  message: "NetherNet Server",
  levelName: "world",
  gameType: 0,
  maxConnections: 40,
  identityPath: "./nethernet.pem",
  identityDomain: "self",
  tlsCertificatePath: null,
  tlsKeyPath: null,
  publicAddress: null,
  publicPort: null,
  requireIdentity: false,
  negotiationTimeout: 15_000,
  inactivityTimeout: 0
};

/**
 * The time in milliseconds a resolved public hostname is cached for.
 */
const HOST_CACHE_TTL = 60_000;

/**
 * The time in milliseconds to wait for local ICE candidates to be gathered.
 */
const GATHERING_TIMEOUT = 5_000;

/**
 * The network identifiers clients may signal with.
 * They are opaque, currently a decimal uint64, so only their length and characters are checked.
 */
const IDENTIFIER_PATTERN = /^[\w.~{}-]{1,128}$/;

/**
 * Whether the libdatachannel logs were routed to a logger.
 */
let loggerInitialized = false;

/**
 * The NetherNet server.
 * Clients first query `GET /v1/join` for the server information, then post their SDP offer to `POST /v1/join/{networkId}`.
 * The answer is generated by a WebRTC peer connection whose UDP traffic is multiplexed on the server port,
 * so every connection shares one TCP and one UDP port.
 */
class Server extends Emitter<NetherNetEvents> {
  /**
   * The nethernet properties for the server instance.
   */
  public readonly properties: NetherNetServerProperties;

  /**
   * The nethernet server logger
   */
  public readonly logger = new Logger("NetherNet", LoggerColors.DarkAqua);

  /**
   * The established connections of the server.
   */
  public readonly connections = new Set<Connection>();

  /**
   * The connections that were answered but did not open their data channels yet.
   */
  public readonly pending = new Set<Connection>();

  /**
   * The operator identity asserted in every SDP answer.
   */
  public identity: OperatorIdentity | null = null;

  /**
   * Overrides the server information returned to clients before they join.
   */
  public statusResolver: (() => Partial<NetherNetStatus>) | null = null;

  /**
   * Whether the server is accepting connections.
   */
  public alive = false;

  /**
   * The HTTP server used for signaling.
   */
  protected http: HttpServer | null = null;

  /**
   * The listener that keeps the multiplexed UDP port bound.
   */
  protected mux: IceUdpMuxListener | null = null;

  /**
   * The libdatachannel binding, loaded when the server starts.
   */
  protected native: NativeBinding | null = null;

  /**
   * The interval checking connections for timeouts.
   */
  protected interval: NodeJS.Timeout | null = null;

  /**
   * Resolved public hostnames, by hostname.
   */
  protected readonly hosts = new Map<
    string,
    { addresses: Array<string>; expires: number }
  >();

  /**
   * The address the nethernet server is bound to.
   */
  public get address(): string {
    return this.properties.address;
  }

  /**
   * The address the nethernet server is bound to.
   */
  public set address(value: string) {
    this.properties.address = value;
  }

  /**
   * The port the nethernet server is bound to.
   */
  public get port(): number {
    return this.properties.port;
  }

  /**
   * The port the nethernet server is bound to.
   */
  public set port(value: number) {
    this.properties.port = value;
  }

  /**
   * The protocol version of the server.
   */
  public get protocol(): number {
    return this.properties.protocol;
  }

  /**
   * The protocol version of the server.
   */
  public set protocol(value: number) {
    this.properties.protocol = value;
  }

  /**
   * The version of the server.
   */
  public get version(): string {
    return this.properties.version;
  }

  /**
   * The version of the server.
   */
  public set version(value: string) {
    this.properties.version = value;
  }

  /**
   * The message of the day of the server.
   */
  public get message(): string {
    return this.properties.message;
  }

  /**
   * The message of the day of the server.
   */
  public set message(value: string) {
    this.properties.message = value;
  }

  /**
   * The max connections of the server.
   */
  public get maxConnections(): number {
    return this.properties.maxConnections;
  }

  /**
   * The max connections of the server.
   */
  public set maxConnections(value: number) {
    this.properties.maxConnections = value;
  }

  /**
   * The address WebRTC binds to, or undefined to bind to every interface.
   */
  protected get bindAddress(): string | undefined {
    const { address } = this.properties;

    return address === "0.0.0.0" || address === "::" ? undefined : address;
  }

  /**
   * Creates a new nethernet server
   * @param properties The properties of the server
   */
  public constructor(properties?: Partial<NetherNetServerProperties>) {
    super();

    // Assign the server properties with the default properties
    this.properties = { ...DefaultNetherNetServerProperties, ...properties };

    // Log errors thrown by event listeners
    this.onError((error) =>
      this.logger.error("An error occurred while emitting an event:", error)
    );
  }

  /**
   * Starts the server
   */
  public async start(): Promise<void> {
    // Load the WebRTC implementation
    const native = await loadNativeBinding();
    this.native = native;

    // Load the operator identity, generating one if needed
    const { identity, generated } = OperatorIdentity.load(
      this.properties.identityPath,
      this.properties.identityDomain
    );
    this.identity = identity;

    if (generated && this.properties.identityPath)
      this.logger.info(
        `Generated a new operator key at §u${this.properties.identityPath}§r (§u${identity.fingerprint}§r). Keep it, players are asked to trust it when they first join.`
      );
    else if (generated)
      this.logger.warn(
        `The operator key is not saved, players are asked to trust the server again after every restart.`
      );
    else this.logger.debug(`Loaded operator key §u${identity.fingerprint}§r.`);

    // Route the libdatachannel logs to the debug log
    // Its errors are about single connections failing to negotiate, so only fatal ones are warnings
    if (!loggerInitialized) {
      loggerInitialized = true;
      native.initLogger("Warning", (level, message) =>
        level === "Fatal"
          ? this.logger.warn(`libdatachannel: ${message}`)
          : this.logger.debug(`libdatachannel: ${message}`)
      );
    }

    // Bind the multiplexed UDP port now, so it is known to be usable and ready for the first connection
    this.mux = new native.IceUdpMuxListener(this.port, this.bindAddress);
    this.mux.onUnhandledStunRequest((request) =>
      this.logger.debug(
        `Ignored a STUN request from §u${request.host}§r:§u${request.port}§r for an unknown connection.`
      )
    );

    // Create the signaling server, over HTTPS when a certificate is configured
    const { tlsCertificatePath, tlsKeyPath } = this.properties;
    const handler = this.handle.bind(this);
    const http =
      tlsCertificatePath && tlsKeyPath
        ? createHttpsServer(
            {
              cert: readFileSync(resolve(tlsCertificatePath)),
              key: readFileSync(resolve(tlsKeyPath))
            },
            handler
          )
        : createHttpServer(handler);

    // Bound the time a signaling request can take
    http.headersTimeout = 10_000;
    http.requestTimeout = 15_000;

    // Close malformed requests straight away; clients try HTTPS before HTTP, and fall back faster this way
    http.on("clientError", (_error, socket) => socket.destroy());

    // Start listening for signaling requests
    await new Promise<void>((resolve, reject) => {
      http.once("error", reject);
      http.listen(this.port, this.address, () => {
        http.off("error", reject);
        resolve();
      });
    });

    http.on("error", (error) => this.emit("error", error));
    this.http = http;
    this.alive = true;

    // Check the connections for timeouts
    this.interval = setInterval(() => this.tick(), TICK_INTERVAL);
    this.interval.unref();
  }

  /**
   * Stops the server
   */
  public stop(): void {
    // Set the server to not alive
    this.alive = false;

    // Disconnect all connections
    for (const connection of [...this.pending, ...this.connections])
      connection.disconnect();

    // Clear the interval
    if (this.interval) {
      clearInterval(this.interval);
      this.interval = null;
    }

    // Close the signaling server
    if (this.http) {
      this.http.close();
      this.http.closeAllConnections?.();
      this.http = null;
    }

    // Release the multiplexed UDP port
    if (this.mux) {
      this.mux.stop();
      this.mux = null;
    }

    // Release libdatachannel, whose logger callback would otherwise keep the process alive
    // This waits for the closing connections to flush their last messages, such as a disconnect reason
    const native = this.native;
    if (!native) return;

    setTimeout(() => {
      // Check if the server was started again in the meantime
      if (this.alive) return;

      native.cleanup();
      loggerInitialized = false;
    }, 500);
  }

  /**
   * Gets the server information returned to clients before they join.
   * @returns The server information.
   */
  public getStatus(): NetherNetStatus {
    return {
      name: this.properties.message,
      protocol: this.properties.protocol,
      version: this.properties.version,
      level: this.properties.levelName,
      players: this.connections.size,
      maxPlayers: this.properties.maxConnections,
      gameType: this.properties.gameType,
      ...this.statusResolver?.()
    };
  }

  /**
   * Handles a connection opening its reliable data channel.
   * @param connection The connection that opened.
   */
  public onOpen(connection: Connection): void {
    this.pending.delete(connection);
    this.connections.add(connection);

    this.logger.debug(
      `Connection §u${connection.identifier}§r established from §u${connection.rinfo.address}§r:§u${connection.rinfo.port}§r in §u${Date.now() - connection.createdAt}ms§r.`
    );

    void this.emit("connect", connection);
  }

  /**
   * Handles a connection closing.
   * @param connection The connection that closed.
   * @param connected Whether the connection was established.
   */
  public onClose(connection: Connection, connected: boolean): void {
    this.pending.delete(connection);
    this.connections.delete(connection);

    if (connected) void this.emit("disconnect", connection);
  }

  /**
   * Closes the connections that timed out.
   */
  protected tick(): void {
    const now = Date.now();
    const { negotiationTimeout, inactivityTimeout } = this.properties;

    // Close the connections that never opened their data channels
    for (const connection of this.pending) {
      if (now - connection.createdAt < negotiationTimeout) continue;

      this.logger.debug(
        `Connection §u${connection.identifier}§r from §u${connection.rinfo.address}§r did not open its data channels in time.`
      );

      connection.disconnect();
    }

    // Close the connections that stopped sending messages
    if (inactivityTimeout <= 0) return;
    for (const connection of this.connections) {
      if (now - connection.lastUpdate < inactivityTimeout) continue;

      this.logger.debug(
        `Connection §u${connection.identifier}§r from §u${connection.rinfo.address}§r timed out.`
      );

      connection.disconnect();
    }
  }

  /**
   * Handles a signaling request.
   * @param request The HTTP request.
   * @param response The HTTP response.
   */
  protected handle(request: IncomingMessage, response: ServerResponse): void {
    const { pathname } = new URL(request.url ?? "/", "http://localhost");

    // The server information, queried before joining
    if (pathname === JOIN_PATH) {
      if (request.method !== "GET" && request.method !== "HEAD")
        return respond(response, 405, "Method not allowed.");

      return respond(
        response,
        200,
        JSON.stringify(this.getStatus()),
        "application/json"
      );
    }

    // The SDP offer of a joining client
    if (pathname.startsWith(`${JOIN_PATH}/`)) {
      if (request.method !== "POST")
        return respond(response, 405, "Method not allowed.");

      return this.signal(
        request,
        response,
        pathname.slice(JOIN_PATH.length + 1)
      );
    }

    return respond(response, 404, "Not found.");
  }

  /**
   * Handles the SDP offer of a joining client.
   * @param request The HTTP request.
   * @param response The HTTP response.
   * @param path The network identifier path segment of the request.
   */
  protected signal(
    request: IncomingMessage,
    response: ServerResponse,
    path: string
  ): void {
    // Check if the server is accepting connections
    if (!this.alive) return respond(response, 503, "Server is not running.");

    // Validate the network identifier of the client
    let identifier: string;
    try {
      identifier = decodeURIComponent(path);
    } catch {
      return respond(response, 400, "Invalid network identifier.");
    }
    if (!IDENTIFIER_PATTERN.test(identifier))
      return respond(response, 400, "Invalid network identifier.");

    // Reject the offer early when the server is full
    if (this.pending.size + this.connections.size >= this.maxConnections)
      return respond(response, 503, "Server is full.");

    // Bound the negotiations a single address can run at once
    const rinfo = getRemoteAddress(request);
    let negotiating = 0;
    for (const connection of this.pending)
      if (connection.rinfo.address === rinfo.address) negotiating++;
    if (negotiating >= MAX_PENDING_PER_ADDRESS)
      return respond(response, 429, "Too many pending connections.");

    // Read the SDP offer, bounding its size
    const chunks: Array<Buffer> = [];
    let size = 0;
    let rejected = false;

    request.on("data", (chunk: Buffer) => {
      if (rejected) return;
      size += chunk.byteLength;

      if (size > MAX_SIGNAL_SIZE) {
        rejected = true;
        response.setHeader("Connection", "close");

        return respond(response, 413, "SDP offer is too large.");
      }

      chunks.push(chunk);
    });

    request.on("error", () => (rejected = true));

    request.on("end", () => {
      if (rejected) return;

      const offer = Buffer.concat(chunks, size).toString("utf8");
      if (!offer.startsWith("v="))
        return respond(response, 400, "Missing SDP offer.");

      // Verify the identity the client asserted, before spending any resources on it
      let identity: ClientIdentity | null;
      try {
        identity = verifyClientIdentity(offer);
      } catch (reason) {
        this.logger.debug(
          `Rejected the offer of §u${rinfo.address}§r, its identity is invalid: ${(reason as Error).message}`
        );

        return respond(response, 403, "Invalid identity assertion.");
      }

      if (!identity && this.properties.requireIdentity)
        return respond(response, 403, "An identity assertion is required.");

      // Answer the offer
      this.negotiate(identifier, offer, identity, rinfo, request.headers.host)
        .then((answer) => respond(response, 200, answer, "application/sdp"))
        .catch((reason) => {
          this.logger.debug(
            `Failed to answer the offer of §u${rinfo.address}§r:`,
            reason
          );

          respond(response, 500, "Failed to answer the SDP offer.");
        });
    });
  }

  /**
   * Answers an SDP offer with a new connection.
   * @param identifier The network identifier of the client.
   * @param offer The SDP offer of the client.
   * @param identity The identity the client proved, if any.
   * @param rinfo The signaling address of the client.
   * @param host The host the client used to reach the signaling server.
   * @returns The SDP answer.
   */
  protected async negotiate(
    identifier: string,
    offer: string,
    identity: ClientIdentity | null,
    rinfo: NetworkAddress,
    host?: string
  ): Promise<string> {
    // Check if the WebRTC implementation was loaded
    if (!this.native) throw new Error("The server has not been started.");

    // Create the peer connection on the multiplexed UDP port
    // No STUN or TURN servers are used, so gathering completes immediately
    const peer: PeerConnection = new this.native.PeerConnection(
      `nethernet-${identifier}`,
      {
        iceServers: [],
        bindAddress: this.bindAddress,
        enableIceUdpMux: true,
        portRangeBegin: this.port,
        portRangeEnd: this.port,
        maxMessageSize: MAX_MESSAGE_SIZE
      }
    );

    // Track the connection while it negotiates
    const connection = new Connection(this, peer, identifier, identity, rinfo);
    this.pending.add(connection);

    try {
      // Apply the offer without its identity, which WebRTC does not understand
      // The answer is generated automatically once the offer is applied
      peer.setRemoteDescription(removeIdentity(offer), "offer");
      await gathered(peer);

      const local = peer.localDescription();
      if (!local) throw new Error("No local description was generated.");

      // Add the address the client reached the server at, and assert the operator identity
      const candidates = await this.getPublicCandidates(local.sdp, host);
      const answer = insertCandidates(local.sdp, candidates);

      return insertIdentity(answer, this.identity!.assert(answer));
    } catch (reason) {
      connection.disconnect();

      throw reason;
    }
  }

  /**
   * Gets candidates for the address clients reach the server at, which the local candidates may not include.
   * Unless a public address is configured, the host the client signaled to is used, so a server behind NAT
   * is reachable without any configuration. These candidates are ranked first, so they are checked first.
   * @param sdp The SDP answer, holding the local candidates.
   * @param host The host the client used to reach the signaling server.
   * @returns The candidate attributes to add.
   */
  protected async getPublicCandidates(
    sdp: string,
    host?: string
  ): Promise<Array<string>> {
    const target = parseHost(host);
    const hostname = this.properties.publicAddress ?? target?.hostname;
    if (!hostname) return [];

    // The client reached the signaling port through the same mapping as the UDP port
    const port = this.properties.publicPort ?? target?.port ?? this.port;
    const addresses = isIP(hostname)
      ? [hostname]
      : await this.resolveHost(hostname);
    const existing = getCandidateAddresses(sdp);
    const candidates: Array<string> = [];

    for (const address of addresses) {
      const normalized = address.toLowerCase();
      if (existing.has(normalized)) continue;
      if (normalized === "0.0.0.0" || normalized === "::") continue;
      existing.add(normalized);

      // Rank the candidate above the host candidates
      const priority = 2130706431 - candidates.length;
      candidates.push(
        `candidate:${9000 + candidates.length} 1 UDP ${priority} ${address} ${port} typ srflx raddr 0.0.0.0 rport 0`
      );
    }

    return candidates;
  }

  /**
   * Resolves a public hostname, caching the result.
   * @param hostname The hostname to resolve.
   * @returns The addresses of the hostname.
   */
  protected async resolveHost(hostname: string): Promise<Array<string>> {
    const cached = this.hosts.get(hostname);
    if (cached && cached.expires > Date.now()) return cached.addresses;

    try {
      const results = await lookup(hostname, { all: true });
      const addresses = results.map((result) => result.address);
      this.hosts.set(hostname, {
        addresses,
        expires: Date.now() + HOST_CACHE_TTL
      });

      return addresses;
    } catch {
      return [];
    }
  }
}

/**
 * Waits for a peer connection to gather its local candidates.
 * @param peer The peer connection.
 */
function gathered(peer: PeerConnection): Promise<void> {
  return new Promise((resolve, reject) => {
    if (peer.gatheringState() === "complete") return resolve();

    const timeout = setTimeout(
      () => reject(new Error("Timed out gathering local candidates.")),
      GATHERING_TIMEOUT
    );

    peer.onGatheringStateChange((state) => {
      if (state !== "complete") return;
      clearTimeout(timeout);
      resolve();
    });
  });
}

/**
 * Writes a complete HTTP response.
 * @param response The HTTP response.
 * @param status The status code.
 * @param body The body.
 * @param type The content type of the body.
 */
function respond(
  response: ServerResponse,
  status: number,
  body: string,
  type = "text/plain"
): void {
  if (response.headersSent) return;

  response.writeHead(status, {
    "Content-Type": type,
    "Content-Length": Buffer.byteLength(body),
    "Cache-Control": "no-store"
  });

  response.end(body);
}

/**
 * Gets the remote address of a signaling request.
 * @param request The HTTP request.
 * @returns The remote address.
 */
function getRemoteAddress(request: IncomingMessage): NetworkAddress {
  // Unwrap IPv4 addresses mapped into IPv6
  const address = (request.socket.remoteAddress ?? "").replace(/^::ffff:/, "");

  return {
    address,
    port: request.socket.remotePort ?? 0,
    family: address.includes(":") ? "IPv6" : "IPv4"
  };
}

/**
 * Parses the host header of a request.
 * @param host The host header.
 * @returns The hostname and port, or null if the header is missing or malformed.
 */
function parseHost(
  host?: string
): { hostname: string; port: number | null } | null {
  if (!host) return null;

  // IPv6 literals are enclosed in brackets
  const match =
    /^\[([^\]]+)\](?::(\d+))?$/.exec(host) ?? /^([^:]+)(?::(\d+))?$/.exec(host);
  if (!match) return null;

  return { hostname: match[1]!, port: match[2] ? Number(match[2]) : null };
}

export { Server };
